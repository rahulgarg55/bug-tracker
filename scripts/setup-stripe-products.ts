/**
 * BugTracker - Stripe Product & Price Setup Script
 *
 * Automatically provisions the official BugTracker SaaS products and prices
 * in your Stripe account (test or live) and prints/appends the required environment variables.
 *
 * Usage:
 *   npx tsx scripts/setup-stripe-products.ts [STRIPE_SECRET_KEY]
 */

import Stripe from "stripe";
import * as fs from "fs";
import * as path from "path";

async function main() {
  const secretKeyArg = process.argv[2];
  const envPath = path.resolve(process.cwd(), ".env");

  let secretKey = secretKeyArg;
  if (!secretKey && fs.existsSync(envPath)) {
    const envContent = fs.readFileSync(envPath, "utf-8");
    const match = envContent.match(/STRIPE_SECRET_KEY=["']?([^"'\r\n]+)["']?/);
    if (match) {
      secretKey = match[1].trim();
    }
  }

  if (!secretKey) {
    console.error("❌ Error: No STRIPE_SECRET_KEY found.");
    console.log("Usage: npx tsx scripts/setup-stripe-products.ts <sk_test_... or sk_live_...>");
    console.log("Or set STRIPE_SECRET_KEY in your .env file.");
    process.exit(1);
  }

  const isLive = secretKey.startsWith("sk_live_");
  console.log(`🔌 Connecting to Stripe in ${isLive ? "LIVE 🔴" : "TEST 🟡"} mode...`);
  const stripe = new Stripe(secretKey);

  console.log("📦 Provisioning BugTracker SaaS products and pricing tiers...\n");

  // 1. Team Product
  console.log("Creating/Fetching 'BugTracker Team' product...");
  const teamProduct = await stripe.products.create({
    name: "BugTracker Team",
    description: "Issue tracking, agile sprints, and board workflows for up to 10 seats.",
    metadata: { planKey: "TEAM" },
  });

  const priceTeamMonthly = await stripe.prices.create({
    product: teamProduct.id,
    unit_amount: 1200, // $12.00
    currency: "usd",
    recurring: { interval: "month", interval_count: 1 },
    nickname: "Team Monthly ($12/mo)",
  });

  const priceTeamYearly = await stripe.prices.create({
    product: teamProduct.id,
    unit_amount: 12000, // $120.00
    currency: "usd",
    recurring: { interval: "year", interval_count: 1 },
    nickname: "Team Yearly ($120/yr)",
  });

  const priceTeamExtraSeatMonthly = await stripe.prices.create({
    product: teamProduct.id,
    unit_amount: 800, // $8.00 / extra seat / month
    currency: "usd",
    recurring: { interval: "month", interval_count: 1 },
    nickname: "Team Extra Seat Monthly ($8/seat/mo)",
  });

  const priceTeamExtraSeatYearly = await stripe.prices.create({
    product: teamProduct.id,
    unit_amount: 8000, // $80.00 / extra seat / year
    currency: "usd",
    recurring: { interval: "year", interval_count: 1 },
    nickname: "Team Extra Seat Yearly ($80/seat/yr)",
  });

  // 2. Business Product
  console.log("Creating/Fetching 'BugTracker Business' product...");
  const businessProduct = await stripe.products.create({
    name: "BugTracker Business",
    description: "Enterprise SLAs, SSO-ready, unlimited automations and up to 25 seats.",
    metadata: { planKey: "BUSINESS" },
  });

  const priceBusinessMonthly = await stripe.prices.create({
    product: businessProduct.id,
    unit_amount: 2900, // $29.00
    currency: "usd",
    recurring: { interval: "month", interval_count: 1 },
    nickname: "Business Monthly ($29/mo)",
  });

  const priceBusinessYearly = await stripe.prices.create({
    product: businessProduct.id,
    unit_amount: 29000, // $290.00
    currency: "usd",
    recurring: { interval: "year", interval_count: 1 },
    nickname: "Business Yearly ($290/yr)",
  });

  const priceBusinessExtraSeatMonthly = await stripe.prices.create({
    product: businessProduct.id,
    unit_amount: 1200, // $12.00 / extra seat / month
    currency: "usd",
    recurring: { interval: "month", interval_count: 1 },
    nickname: "Business Extra Seat Monthly ($12/seat/mo)",
  });

  const priceBusinessExtraSeatYearly = await stripe.prices.create({
    product: businessProduct.id,
    unit_amount: 12000, // $120.00 / extra seat / year
    currency: "usd",
    recurring: { interval: "year", interval_count: 1 },
    nickname: "Business Extra Seat Yearly ($120/seat/yr)",
  });

  const envVariables = `
# Stripe Billing Configuration (Auto-Generated by setup-stripe-products)
BILLING_PROVIDER="stripe"
STRIPE_SECRET_KEY="${secretKey}"
STRIPE_LIVE_MODE_APPROVED="${isLive ? "true" : "false"}"

# Team Plan Prices ($12/mo, $120/yr, $8 extra seat)
STRIPE_PRICE_TEAM_MONTHLY="${priceTeamMonthly.id}"
STRIPE_PRICE_TEAM_YEARLY="${priceTeamYearly.id}"
STRIPE_PRICE_TEAM_EXTRA_SEAT_MONTHLY="${priceTeamExtraSeatMonthly.id}"
STRIPE_PRICE_TEAM_EXTRA_SEAT_YEARLY="${priceTeamExtraSeatYearly.id}"

# Business Plan Prices ($29/mo, $290/yr, $12 extra seat)
STRIPE_PRICE_BUSINESS_MONTHLY="${priceBusinessMonthly.id}"
STRIPE_PRICE_BUSINESS_YEARLY="${priceBusinessYearly.id}"
STRIPE_PRICE_BUSINESS_EXTRA_SEAT_MONTHLY="${priceBusinessExtraSeatMonthly.id}"
STRIPE_PRICE_BUSINESS_EXTRA_SEAT_YEARLY="${priceBusinessExtraSeatYearly.id}"
`;

  console.log("\n=======================================================");
  console.log("✅ All Stripe Products & Prices Created Successfully!");
  console.log("=======================================================\n");
  console.log(envVariables);

  if (fs.existsSync(envPath)) {
    fs.appendFileSync(envPath, `\n${envVariables}\n`);
    console.log(`📁 Appended configuration directly to: ${envPath}`);
  } else {
    fs.writeFileSync(envPath, envVariables);
    console.log(`📁 Created: ${envPath}`);
  }

  console.log("\nNext Steps:");
  console.log("1. Add your STRIPE_PUBLISHABLE_KEY and STRIPE_WEBHOOK_SECRET to .env");
  console.log("2. Set APP_BASE_URL to your public domain (e.g. http://localhost:3001 or production domain)");
  console.log("3. Configure webhook endpoint in Stripe Dashboard -> Webhooks -> Add endpoint: /api/webhooks/stripe");
}

main().catch((err) => {
  console.error("❌ Failed to setup Stripe products:", err);
  process.exit(1);
});
